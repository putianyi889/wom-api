"""Generate explicit Python methods and endpoint docs from reviewed metadata."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

if __package__:
    from .type_info import field_schemas, python_type
else:
    from type_info import field_schemas, python_type

ROOT = Path(__file__).resolve().parents[1]


def type_table(api: dict, direction: str) -> list[str]:
    schema = api[f"{direction}_schema"]
    if not schema:
        return [f"{direction.title()} type: `JsonValue` (unresolved).", ""]
    root_type = python_type(schema).replace("|", "\\|")
    rows = [f"{direction.title()} type: `{root_type}`.", ""]
    fields = list(field_schemas(schema))
    if not fields:
        return rows
    rows += ["| Field path | Python type | Evidence |", "| --- | --- | --- |"]
    for path, field in fields:
        evidence = ", ".join(api[f"{direction}_type_sources"].get(path, [])) or "unresolved"
        annotation = python_type(field).replace("|", "\\|")
        if annotation == "None":
            evidence += "; only null observed"
        rows += [f"| `{path}` | `{annotation}` | {evidence} |"]
    return [*rows, ""]


def render(catalog: dict) -> dict[Path, str]:
    code = [
        "# Generated by tools/generate.py. Review api_catalog.json before regenerating.",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from typing import Protocol",
        "",
        "from .types import JsonValue",
        "",
        "",
        "class _Requester(Protocol):",
        "    async def request(",
        "        self, controller: str, payload: Mapping[str, JsonValue] | None = None,",
        "        *, server: str | None = None, timeout: float | None = None,",
        "        **params: JsonValue,",
        "    ) -> JsonValue: ...",
        "",
        "",
        "class ApiMethods(_Requester):",
        '    """One Python entry point per observed browser controller.',
        "",
        "    Supply a mapping or wire-name keyword arguments. See the endpoint",
        "    catalogue for observed fields and permissions.",
        '    """',
    ]
    docs = [
        "# Endpoint catalogue",
        "",
        f"Generated from frontend version **{catalog['version']}**; "
        f"**{len(catalog['apis'])}** controllers. Each method is async and returns "
        "the original JSON value.",
        "",
        "All methods accept `payload=None`, keyword-only `server=None`, "
        "`timeout=None`, and `**params`. Parameter names in `params` use the "
        "original camelCase wire names. A mapping is necessary if a wire field "
        "collides with `payload`, `server`, or `timeout`.",
        "",
        "Field lists below are observations from browser call sites, **not** "
        "required-field schemas. Different requests may use different subsets; "
        "unknown or dynamic shapes are stated explicitly. Empty response field "
        "lists mean the browser callback did not reveal a destructured shape. "
        "Account, chat, game and administrator actions need the corresponding "
        "server permissions. Inclusion does not grant access.",
        "",
        "Types below describe **observed or inferred JSON types**, not exhaustive "
        "server contracts. `frontend syntax` means literals or explicit JavaScript "
        "conversions; `live sample` means type-only schemas merged from successful "
        "public requests/responses. `JsonValue` with `unresolved` means a field's "
        "concrete type is unknown. A type observed in one sample can have other "
        "variants that have not been seen. `None` alone means only null was "
        "observed, not that null is the only valid value. None is a value, "
        "not evidence that a field is optional.",
        "",
        "Types use Python notation: `int`, `int | float` (JSON number), `bool`, "
        "`str`, `None`, `list[T]`, and `dict[str, JsonValue]`. A path such as "
        "`result[].id` describes an array item's field. Date/time strings remain "
        "`str`. Live sampling is opt-in; documentation builds are offline. "
        "[Type evidence and update procedure](research/README.md#field-type-evidence).",
        "",
    ]
    for api in catalog["apis"]:
        name = api["method"]
        code += [
            "",
            f"    async def {name}(",
            "        self, payload: Mapping[str, JsonValue] | None = None,",
            "        *, server: str | None = None, timeout: float | None = None,",
            "        **params: JsonValue,",
            "    ) -> JsonValue:",
            f'        """Call {api["controller"]} on the {api["role"]} role."""',
            f'        return await self.request("{api["controller"]}", payload,',
            "                                  server=server, timeout=timeout, **params)",
        ]
        docs += [
            f"## {name}",
            "",
            f"Controller: `{api['controller']}`. Role: **{api['role']}**.",
            "",
        ]
        if api["role"] == "game":
            docs += [
                "Pass `server=` using the game metadata. "
                "The client cannot infer it from a game ID.",
                "",
            ]
        if api["closes_session"]:
            docs += ["The browser marks this action as closing a session.", ""]
        if api["controller"].startswith("Admin"):
            docs += ["Requires administrator permission.", ""]
        if api["observed_requests"]:
            docs += ["Observed request shapes:", ""]
            for shape in api["observed_requests"]:
                docs += ["- " + ", ".join(f"`{key}`" for key in shape["fields"])]
                if shape["literals"]:
                    docs[-1] += (
                        "; observed literals: `"
                        + json.dumps(shape["literals"], ensure_ascii=False)
                        + "`"
                    )
            docs += [""]
        else:
            docs += [
                "Request shape: no inline object resolved; "
                "may be empty or constructed dynamically.",
                "",
            ]
        response = api["observed_response_fields"]
        docs += [
            "Observed response fields: "
            + (", ".join(f"`{key}`" for key in response) if response else "not resolved")
            + ".",
            "",
        ]
        if api["table_query_fields"]:
            docs += ["Observed nested `params` shapes:", ""]
            docs += [
                "- " + ", ".join(f"`{k}`" for k in shape) for shape in api["table_query_fields"]
            ]
            docs += ["", "Table `dataType`: 1 = count, 2 = current player position, 3 = rows.", ""]
        if api["table_sorts"]:
            docs += [
                "Observed default table sort keys: "
                + ", ".join(f"`{k}`" for k in api["table_sorts"])
                + ".",
                "",
            ]
        docs += type_table(api, "request")
        docs += type_table(api, "response")
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", "_generated.py", "-"],
        input="\n".join(code) + "\n",
        text=True,
        capture_output=True,
        check=True,
        cwd=ROOT,
    ).stdout
    return {
        ROOT / "src/wom_api/_generated.py": formatted,
        ROOT / "docs/endpoints.md": "\n".join(docs),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads((ROOT / "src/wom_api/api_catalog.json").read_text(encoding="utf-8"))
    for path, content in render(catalog).items():
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale generated file: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print(f"Generated files match {len(catalog['apis'])} controllers")


if __name__ == "__main__":
    main()
